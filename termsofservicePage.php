        function toggleSidebar() {
            const sidebar = document.getElementById('sidebar');
            sidebar.classList.toggle('-translate-x-full');
        }

        // Close sidebar on mobile when clicking outside (simple implementation)
        window.addEventListener('click', (e) => {
            const sidebar = document.getElementById('sidebar');
            const menuBtn = document.querySelector('.material-symbols-outlined[onclick="toggleSidebar()"]');
            if (window.innerWidth < 768 && !sidebar.contains(e.target) && e.target !== menuBtn) {
                sidebar.classList.add('-translate-x-full');
            }
        });

        // Smooth scroll spy for active state in sidebar (optional enhancement)
        const sections = document.querySelectorAll('div[id]');
        const navLinks = document.querySelectorAll('aside nav ul li a');

        window.addEventListener('scroll', () => {
            let current = '';
            sections.forEach(section => {
                const sectionTop = section.offsetTop;
                const sectionHeight = section.clientHeight;
                if (pageYOffset >= (sectionTop - 150)) {
                    current = section.getAttribute('id');
                }
            });

            navLinks.forEach(link => {
                link.classList.remove('text-primary', 'font-bold');
                if (link.getAttribute('href').includes(current)) {
                    link.classList.add('text-primary', 'font-bold');
                }
            });
        });
